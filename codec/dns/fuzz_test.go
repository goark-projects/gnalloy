package dns

import "testing"

const maxDNSFuzzInput = 4096

func FuzzDNSParseMessage(f *testing.F) {
	f.Add([]byte{
		0x12, 0x34, 0x01, 0x00, 0x00, 0x01, 0x00, 0x00,
		0x00, 0x00, 0x00, 0x00, 0x07, 'e', 'x', 'a',
		'm', 'p', 'l', 'e', 0x03, 'c', 'o', 'm', 0x00,
		0x00, 0x01, 0x00, 0x01,
	})
	f.Add([]byte{
		0x12, 0x34, 0x81, 0x80, 0x00, 0x01, 0x00, 0x01,
		0x00, 0x00, 0x00, 0x00, 0x07, 'e', 'x', 'a',
		'm', 'p', 'l', 'e', 0x03, 'c', 'o', 'm', 0x00,
		0x00, 0x01, 0x00, 0x01, 0xc0, 0x0c, 0x00, 0x01,
		0x00, 0x01, 0x00, 0x00, 0x00, 0x3c, 0x00, 0x04,
		127, 0, 0, 1,
	})
	f.Add([]byte{0, 1, 0x81, 0x80, 0, 0, 0, 0, 0, 0, 0, 0})
	f.Fuzz(func(t *testing.T, data []byte) {
		if len(data) > maxDNSFuzzInput {
			return
		}
		msg, err := ParseMessage(data)
		if err != nil {
			return
		}
		encoded, err := AppendMessage(nil, msg)
		if err != nil {
			return
		}
		if _, err := ParseMessage(encoded); err != nil {
			t.Fatalf("parse appended message: %v", err)
		}
	})
}
